def get_tooltip(term: str) -> Optional[str]:
    """Return the glossary definition for *term*, or *None* if not found."""
    return TRADING_GLOSSARY.get(term) or TRADING_GLOSSARY.get(term.lower())


def create_tooltip_label(
    text: str,
    tooltip_term: str,
    parent: Optional[QWidget] = None,
) -> QLabel:
    """Create a QLabel with a dotted-underline hint and a glossary tooltip.

    The label text is rendered in gold with a dotted underline to signal
    that a hover-tooltip is available.
    """
    definition = get_tooltip(tooltip_term)
    lbl = QLabel(text, parent)
    lbl.setToolTip(definition or tooltip_term)
    lbl.setStyleSheet(
        f"color: {COLORS['gold']}; "
        f"text-decoration: underline; "
        f"text-decoration-style: dotted; "
        f"text-decoration-color: {COLORS['gold_dim']}; "
        f"font-family: 'Segoe UI'; "
    )
    lbl.setCursor(Qt.CursorShape.WhatsThisCursor)
    return lbl
